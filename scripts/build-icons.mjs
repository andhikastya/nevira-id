// Builds a Remix Icon subset containing only the `ri-*` icons used in the source.
// The full remixicon.css is ~157 KB of render-blocking CSS (+190 KB font) for ~55 icons.
//
// Run after adding or changing an icon:  pnpm icons
// Outputs: app/remixicon-subset.css, public/fonts/remixicon-subset.woff2
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, extname } from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SRC_DIRS = ["app", "components", "content", "lib"];
const RI = join(ROOT, "node_modules/remixicon/fonts");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if ([".ts", ".tsx", ".js", ".jsx", ".mdx"].includes(extname(p))) out.push(p);
  }
  return out;
}

const used = new Set();
for (const d of SRC_DIRS) for (const f of walk(join(ROOT, d))) for (const m of readFileSync(f, "utf8").matchAll(/\bri-[a-z0-9]+(?:-[a-z0-9]+)*/g)) used.add(m[0]);

const css = readFileSync(join(RI, "remixicon.css"), "utf8");
const glyphs = new Map(); // class -> codepoint hex
for (const m of css.matchAll(/\.(ri-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}/g)) glyphs.set(m[1], m[2]);

const icons = [...used].filter((c) => glyphs.has(c)).sort();
const unknown = [...used].filter((c) => !glyphs.has(c));
if (unknown.length) console.warn("Not a Remix icon (ignored):", unknown.join(", "));

const text = icons.map((c) => String.fromCodePoint(parseInt(glyphs.get(c), 16))).join("");
const woff2 = await subsetFont(readFileSync(join(RI, "remixicon.woff2")), text, { targetFormat: "woff2" });
writeFileSync(join(ROOT, "public/fonts/remixicon-subset.woff2"), woff2);

const out = `/* GENERATED by scripts/build-icons.mjs — do not edit. Run \`pnpm icons\` after adding an icon. */
@font-face {
  font-family: "remixicon";
  src: url("/fonts/remixicon-subset.woff2") format("woff2");
  font-display: block;
}
[class^="ri-"],
[class*=" ri-"] {
  font-family: "remixicon" !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
${icons.map((c) => `.${c}:before { content: "\\${glyphs.get(c)}"; }`).join("\n")}
`;
writeFileSync(join(ROOT, "app/remixicon-subset.css"), out);
console.log(`Remix Icon subset: ${icons.length} icons, font ${(woff2.length / 1024).toFixed(1)} KB`);
